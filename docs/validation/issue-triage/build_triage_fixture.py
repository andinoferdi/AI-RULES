LISTING = '''"""Select and format items for `shelf list`."""


def list_items(items, tag=None):
    """Return all items, or only the items carrying `tag` (case-insensitive)."""
    if tag is None:
        return list(items)
    wanted = tag.lower()
    return [item for item in items if wanted in item.get("tags", [])]


def format_line(item):
    tags = ", ".join(item.get("tags", []))
    line = f"{item['title']} by {item['author'] or 'unknown'}"
    return f"{line} [{tags}]" if tags else line
'''

EXPORT = '''"""Export the shelf for spreadsheets."""

COLUMNS = ("title", "author", "tags")


def export_csv(items):
    """Return the shelf as CSV text with a header row."""
    lines = [",".join(COLUMNS)]
    for item in items:
        lines.append(",".join([item["title"], item["author"], ";".join(item.get("tags", []))]))
    return "\\n".join(lines) + "\\n"


def write_csv(items, path):
    with open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(export_csv(items))
'''

