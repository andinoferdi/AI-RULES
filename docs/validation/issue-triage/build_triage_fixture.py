def item(number, title, *, kind="issue", state="open", author, created, labels, body,
         comments=()):
    text = (f"# #{number} {title}\n\n- type: {kind}\n- state: {state}\n- author: {author}\n"
            f"- created: {created}\n- labels: {labels or '(none)'}\n\n{body.strip()}\n")
    for who, when, comment in comments:
        text += f"\n### {who} commented on {when}\n\n{comment.strip()}\n"
    return text


