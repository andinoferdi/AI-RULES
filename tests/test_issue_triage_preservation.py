"""Guard the andino-issue-triage rewrite against silent loss.

The anchors cover what the 2026-11-26 rewrite adopted from Matt Pocock's triage (attention
buckets, concept checks, verification verdicts, outcome branches, briefs, out-of-scope
records) and the Andino rules it kept (authority before any tracker write, local drafts,
tracker label strings). A failing anchor means a rule or resource was dropped. The test reads
the real skill folder.
"""

import os
import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKILL = ROOT / "skills/andino-workflow/skills/issue-triage"

SECTIONS = ["Purpose", "Trigger and non-trigger", "Select a resource, not a second lifecycle",
            "Prerequisites", "Procedure", "Rules", "Shortcuts", "Red flags",
            "Ownership and permission boundary", "Output", "Verification",
            "Worked example and anti-pattern", "Fallback", "Local resources",
            "Operational example", "Provenance"]

DISCLAIMER = "> *This was generated by AI during triage.*"

ANCHORS = {
    "SKILL.md": [
        DISCLAIMER, "never triaged", "oldest first", "[PR]", "in-flight pull request",
        "by domain concept", "every place you looked", ".out-of-scope/", "CONFIRMED", "FAILED",
        "INSUFFICIENT", "two state labels", "andino-brainstorming", "ready-for-human",
        "already built", "rejected bug", "rejected enhancement", "Move #N to STATE",
        "skip grilling", "authority line", "not posted", "re-read", "Never ask an answered question",
        "tracker's own strings", "starting branch", "an issue with attached code",
    ],
    "resources/agent-brief.md": [
        "file paths or line numbers", "Behavior, not procedure", "Acceptance criteria",
        "Out of scope", "Key interfaces", "what is left to do", "Why a person", "A brief that fails",
        DISCLAIMER,
    ],
    "resources/out-of-scope.md": [
        "one Markdown file per rejected **concept**", "by concept, not by keyword", "Confirm",
        "Reconsider", "Distinct", "already exists", "Never for a bug", "Prior requests",
        "deferral", "kebab-case",
    ],
    "resources/tracker-notes.md": [
        "What we've established so far", "What we still need from you", "Left out",
        "Never \"please provide more information\"", "Already built", "Rejected bug",
        "Rejected enhancement", DISCLAIMER,
    ],
}

# Words from the trial fixture (docs/validation/issue-triage). The skill must not carry them,
# or the trial would measure fit to the fixture instead of the method.
FIXTURE_WORDS = ["shelf", "colour", "night mode", "--tag", "Dune", "csv", "jq"]

FENCE = re.compile(r"^```.*?^```[^\n]*$", re.M | re.S)


def read(rel):
    return (SKILL / rel).read_text(encoding="utf-8")


def prose(text):
    return FENCE.sub("", text)


def body(text):
    """SKILL.md text after the closing frontmatter line."""
    parts = text.split("\n---\n", 1)
    return parts[1].lstrip("\n") if text.startswith("---\n") and len(parts) == 2 else text


def section(text, name):
    match = re.search(rf"^## {re.escape(name)}[^\n]*$(.*?)(?=^## |\Z)", prose(text), re.M | re.S)
    return match.group(1) if match else ""


class IssueTriagePreservationTests(unittest.TestCase):
    def test_sections_in_sibling_order(self):
        found = re.findall(r"^## (.+?)\s*$", prose(body(read("SKILL.md"))), re.M)
        position = 0
        for name in SECTIONS:
            matches = [i for i, heading in enumerate(found) if heading.startswith(name)]
            self.assertTrue(matches, f"missing section: {name}")
            self.assertGreaterEqual(matches[0], position, f"out of order: {name}")
            position = matches[0]

    def test_procedure_steps_have_done_when(self):
        procedure = section(read("SKILL.md"), "Procedure")
        steps = re.split(r"^\d+\. ", procedure, flags=re.M)[1:]
        self.assertEqual(8, len(steps))
        for number, step in enumerate(steps, 1):
            self.assertIn("Done when", step, f"step {number} has no completion check")

    def test_guide_mirrors_skill(self):
        self.assertEqual(body(read("SKILL.md")), read("GUIDE.md").lstrip("\n"),
                         "GUIDE.md must equal the SKILL.md body")

    def test_description_names_triggers_only(self):
        description = re.search(r"^description: (.+)$", read("SKILL.md"), re.M).group(1)
        self.assertTrue(description.startswith("Use when"))
        self.assertLessEqual(len(description), 1024)
        for workflow_word in ("verify", "brief", "out-of-scope"):
            self.assertNotIn(workflow_word, description.lower())

    def test_anchors(self):
        for rel, literals in ANCHORS.items():
            text = " ".join(read(rel).split())  # line wrapping is not content
            for literal in literals:
                with self.subTest(file=rel, anchor=literal):
                    self.assertIn(" ".join(literal.split()), text)

    def test_resource_links_resolve(self):
        for rel in ("SKILL.md", "resources/worked-example.md"):
            for target, anchor in re.findall(r"\]\(([^)#]*\.md)(?:#([^)]*))?\)", read(rel)):
                path = (SKILL / rel).parent / target
                with self.subTest(source=rel, target=target, anchor=anchor):
                    self.assertTrue(path.exists())
                    if anchor:
                        slugs = {re.sub(r"[^a-z0-9 -]", "", h.lower()).replace(" ", "-")
                                 for h in re.findall(r"^#+ (.+?)\s*$",
                                                     path.read_text(encoding="utf-8"), re.M)}
                        self.assertIn(anchor, slugs)

    def test_no_fixture_domain(self):
        for path in sorted(SKILL.rglob("*.md")):
            rel = path.relative_to(SKILL).as_posix()
            if rel == "references/license.md":
                continue
            text = path.read_text(encoding="utf-8").lower()
            for word in FIXTURE_WORDS:
                with self.subTest(file=rel, word=word):
                    self.assertNotIn(word.lower(), text)

    def test_worked_example_keeps_one_python_block(self):
        blocks = re.findall(r"```python\n(.*?)\n```", read("resources/worked-example.md"), re.S)
        self.assertEqual(1, len(blocks), "check_andino_matt_methods.py needs exactly one block")

    def test_operational_example_runs(self):
        match = re.search(r"^```python andino-operational-example\n(.*?)^```", read("SKILL.md"),
                          re.M | re.S)
        self.assertIsNotNone(match, "no operational example")
        with tempfile.TemporaryDirectory() as work:
            script = Path(work) / "example.py"
            script.write_text(match.group(1), encoding="utf-8")
            ok = subprocess.run([sys.executable, str(script)], capture_output=True, text=True)
            self.assertEqual(0, ok.returncode, ok.stderr)
            negative = subprocess.run([sys.executable, str(script)], capture_output=True,
                                      text=True, env=dict(os.environ, ANDINO_NEGATIVE="1"))
            self.assertEqual(1, negative.returncode)


if __name__ == "__main__":
    unittest.main()
